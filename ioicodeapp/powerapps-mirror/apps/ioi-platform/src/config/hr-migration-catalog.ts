export function getHRMigrationStats(apps = HR_MIGRATION_APPS) {
  return apps.reduce(
    (acc, app) => {
      acc.total += 1;
      acc.fields += app.fields;
      acc.enabledAgents += app.enabledAgents;
      acc.disabledAgents += app.disabledAgents;
      acc.aclEntries += app.aclEntries;
      acc.byPriority[app.priority] += 1;
      acc.bySite[app.site] += 1;
      return acc;
    },
    {
      total: 0,
      fields: 0,
      enabledAgents: 0,
      disabledAgents: 0,
      aclEntries: 0,
      byPriority: { P1: 0, P2: 0, P3: 0 },
      bySite: { Johor: 0, Penang: 0 },
    },
  );
}
