export interface AppSettings {
  /**
   * @displayName ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: number;
  /**
   * @displayName Title
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  title: string;
  /**
   * @displayName Category
   */
  categoryKey?: AppSettingsCategoryKey;
  /**
   * @displayName Data Type
   */
  dataTypeKey?: AppSettingsDataTypeKey;
  /**
   * @displayName Description
   */
  description?: string;
  /**
   * @displayName Is Editable
   */
  isEditable?: boolean;
  /**
   * @displayName Setting Key
   * @validationRule Required for create/update operations
   */
  settingKey: string;
  /**
   * @displayName Setting Value
   */
  settingValue?: string;
}

