/**
 * MainDB_STR Shared Columns Schema
 * These columns are on EVERY STR form.
 * Form-specific columns are appended starting at #13.
 */
export interface MainDB_STR_Base {
  // SharePoint System Fields
  id: string;
  guid: string;
  
  /** #1 - Title (SYSTEM-COMPUTED)
   * Formula: '<FORMCODE>-' & INO
   * Used for gallery display */
  Title: string;
  
  /** #2 - INO - Reference Number (SYSTEM-COMPUTED)
   * Pattern: STR-<FORMCODE>-YYMM-NNNN (e.g., STR-ACMSTR-2605-0001)
   * Generated by Power Automate */
  INO: string;
  
  /** #3 - FormType / FormCode (SYSTEM-COMPUTED)
   * Discriminator column - fixed per form, immutable */
  FormType: import('@/config/str-constants').STRFormCode;
  
  /** #4 - CurrentStatus (WORKFLOW-MANAGED)
   * Choices: Draft/Submitted/PendingReview/PendingApproval/Approved/Rejected/Returned/Closed */
  CurrentStatus: import('@/config/str-constants').STRStatus;
  
  /** #5 - EnvironmentTag (SYSTEM-COMPUTED) */
  EnvironmentTag: STREnvironmentTag;
  
  /** #6 - Site (USER-ENTERED)
   * Choices: PRAI/JOHOR */
  Site: STRSite;
  
  /** #7 - Department (USER-ENTERED) */
  Department: string;
  
  /** #8 - Requestor (USER-ENTERED) */
  Requestor: string;
  
  /** #9 - RequestorEmail (USER-ENTERED) */
  RequestorEmail: string;
  
  /** #10 - RequestDate (SYSTEM-COMPUTED) */
  RequestDate: Date;
  
  /** #11 - SubmittedBy (SYSTEM-COMPUTED) - Optional */
  SubmittedBy?: string;
  
  /** #12 - SubmittedByEmail (SYSTEM-COMPUTED) - Optional */
  SubmittedByEmail?: string;
  
  /** #13 - SubmittedDate (SYSTEM-COMPUTED) - Optional */
  SubmittedDate?: Date;
  
  /** #14 - ApprovedBy (WORKFLOW-MANAGED) - Optional */
  ApprovedBy?: string;
  
  /** #15 - ApprovedByEmail (WORKFLOW-MANAGED) - Optional */
  ApprovedByEmail?: string;
  
  /** #16 - ApprovedDate (WORKFLOW-MANAGED) - Optional */
  ApprovedDate?: Date;
  
  /** #17 - Comments (USER-ENTERED) - Optional */
  Comments?: string;
  
  /** #18 - Attachments (USER-ENTERED) - Optional */
  Attachments?: string[];
  
  /** #19 - IsLocked (WORKFLOW-MANAGED) - Optional */
  IsLocked?: boolean;
  
  // System Timestamps
  CreatedDate: Date;
  ModifiedDate: Date;
  CreatedBy: string;
  ModifiedBy: string;
  
  // Form-specific fields (extended per form type)
  ItemDescription?: string;
  Quantity?: number;
  UnitOfMeasure?: string;
  Justification?: string;
  StoreRemarks?: string;
  VerifiedBy?: string;
  VerifiedDate?: Date;
}

// Alias for backwards compatibility
export type MainDBSTRRecord = MainDB_STR_Base;

// =============================================================================
// STR FORM TYPE - For Create/Update Operations
// =============================================================================

export interface STRForm extends Partial<MainDB_STR_Base> {
  FormType: import('@/config/str-constants').STRFormCode;
}

// =============================================================================
// STR APPROVAL RECORD
// =============================================================================

export interface STR_ApprovalRecord {
  id: string;
  guid: string;
  
  /** Parent submission GUID */
  ParentID: string;
  
  /** Form discriminator */
  FormCode: import('@/config/str-constants').STRFormCode;
  
  /** Stage number in workflow */
  StageNumber: number;
  
  /** Stage name for display */
  StageName: string;
  
  /** Action taken: Approve/Reject/Return */
  Action: 'Approve' | 'Reject' | 'Return';
  
  /** Person who took action */
  ActionBy: string;
  
  /** Email of person who took action */
  ActionByEmail: string;
  
  /** When action was taken */
  ActionDate: Date;
  
  /** Comments from approver */
  Comments?: string;
  
  /** Record created timestamp */
  CreatedDate: Date;
}

