<#
.SYNOPSIS
    Creates SharePoint groups from resolved group/member CSV files.

.DESCRIPTION
    Consumes the CSV files generated by Resolve-ITSSRSharePointGroupsFromDxl.ps1
    and creates only the recommended SharePoint groups, then adds the resolved
    member email addresses to each group.
#>

[CmdletBinding(SupportsShouldProcess = $true)]
param(
    [string]$SiteUrl,

    [string]$SummaryCsv = ".\scripts\itssr-sharepoint-groups-from-dxl.csv",

    [string]$MembersCsv = ".\scripts\itssr-sharepoint-group-members-from-dxl.csv",

    [string]$ClientId = "21898567-7d8f-4634-846d-fd4cf7b185db",

    [switch]$DeviceLogin,

    [switch]$PersistLogin,

    [string]$Owner,

    [string]$Role,

    [switch]$StopOnError
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

if (-not $SiteUrl) {
    throw "SiteUrl is required."
}
if (-not (Test-Path -LiteralPath $SummaryCsv)) {
    throw "SummaryCsv '$SummaryCsv' was not found."
}
if (-not (Test-Path -LiteralPath $MembersCsv)) {
    throw "MembersCsv '$MembersCsv' was not found."
}

Import-Module PnP.PowerShell -ErrorAction Stop

$groups = @(
    Import-Csv -LiteralPath $SummaryCsv |
        Where-Object { $_.Recommendation -eq "Create SharePoint group" -and $_.SharePointGroupName } |
        Sort-Object SharePointGroupName -Unique
)
$members = @(
    Import-Csv -LiteralPath $MembersCsv |
        Where-Object { $_.SharePointGroupName -and $_.Email } |
        Sort-Object SharePointGroupName, Email -Unique
)

if ($groups.Count -eq 0) {
    throw "No groups marked for creation were found in '$SummaryCsv'."
}

$params = @{
    Url = $SiteUrl
}
if ($ClientId) {
    $params.ClientId = $ClientId
}
if ($DeviceLogin) {
    $params.DeviceLogin = $true
} else {
    $params.Interactive = $true
}
if ($PersistLogin) {
    $params.PersistLogin = $true
}

Write-Host "Connecting to $SiteUrl ..." -ForegroundColor Cyan
Connect-PnPOnline @params

$createdGroups = 0
$updatedGroups = 0
$memberAdds = 0
$roleGrants = 0
$failures = [System.Collections.Generic.List[object]]::new()

Write-Host "Groups to create/update: $($groups.Count)" -ForegroundColor Cyan
Write-Host "Member assignments:      $($members.Count)" -ForegroundColor Cyan

foreach ($group in $groups) {
    try {
        $groupName = $group.SharePointGroupName
        $descriptionParts = @(
            "Migrated from Domino principal: $($group.DominoPrincipal)"
            if ($group.AccessPurpose) { "Purpose: $($group.AccessPurpose)" }
            if ($group.Description) { "Domino description: $($group.Description)" }
        )
        $description = ($descriptionParts -join " | ")

        $spGroup = Get-PnPGroup -Identity $groupName -ErrorAction SilentlyContinue
        if (-not $spGroup) {
            if ($PSCmdlet.ShouldProcess($SiteUrl, "create SharePoint group '$groupName'")) {
                $newGroupParams = @{
                    Title = $groupName
                    Description = $description
                }
                if ($Owner) {
                    $newGroupParams.Owner = $Owner
                }
                New-PnPGroup @newGroupParams | Out-Null
                $createdGroups++
            }
        } else {
            if ($PSCmdlet.ShouldProcess($groupName, "update SharePoint group description")) {
                $setGroupParams = @{
                    Identity = $groupName
                    Description = $description
                }
                if ($Owner) {
                    $setGroupParams.Owner = $Owner
                }
                Set-PnPGroup @setGroupParams | Out-Null
                $updatedGroups++
            }
        }

        if ($Role) {
            if ($PSCmdlet.ShouldProcess($groupName, "grant site role '$Role'")) {
                Set-PnPGroupPermissions -Identity $groupName -AddRole $Role -ErrorAction Stop
                $roleGrants++
            }
        }

        foreach ($member in @($members | Where-Object { $_.SharePointGroupName -eq $groupName })) {
            try {
                if ($PSCmdlet.ShouldProcess($groupName, "add member '$($member.Email)'")) {
                    Add-PnPGroupMember -Group $groupName -EmailAddress $member.Email -ErrorAction Stop
                    $memberAdds++
                }
            } catch {
                $message = $_.Exception.Message
                if ($message -match "already exists|already a member") {
                    Write-Warning "Member already present in '$groupName': $($member.Email)"
                } else {
                    throw
                }
            }
        }
    } catch {
        $failures.Add([pscustomobject]@{
            SharePointGroupName = $group.SharePointGroupName
            DominoPrincipal = $group.DominoPrincipal
            Error = $_.Exception.Message
        })
        Write-Warning "Failed group '$($group.SharePointGroupName)': $($_.Exception.Message)"
        if ($StopOnError) {
            throw
        }
    }
}

Write-Host "`nCompleted." -ForegroundColor Green
Write-Host "Groups created:        $createdGroups" -ForegroundColor Green
Write-Host "Groups updated:        $updatedGroups" -ForegroundColor Green
Write-Host "Member add operations: $memberAdds" -ForegroundColor Green
Write-Host "Site role grants:      $roleGrants" -ForegroundColor Green
Write-Host "Failures:              $($failures.Count)" -ForegroundColor Green

if ($failures.Count -gt 0) {
    $failures | Format-Table -AutoSize
    exit 1
}
